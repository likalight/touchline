def phrase(lang: str, key: str, persona: str) -> str:
    bank = BANKS.get(lang, EN)
    for k in (f"{key}.{persona}", key):
        if k in bank:
            return bank[k]
    for k in (f"{key}.{persona}", key):
        if k in EN:
            return EN[k]
    return key


